async function start(){
  const preload=mockAi?['--import','./test-ai-provider.mjs']:[];
  server=spawn(process.execPath,[...preload,'server.mjs'],{cwd:root,env:{...process.env,OPENAI_API_KEY:mockAi?'raffah-test-stub':'',PORT:port,RAFFAH_DATA:db,RAFFAH_ORIGIN:qrOrigin},stdio:['ignore','ignore','inherit']});
  for(let i=0;i<150&&server.exitCode===null;i++){try{if((await fetch(origin)).ok)return;}catch{}await sleep(200);}
  throw new Error('Server failed to start');
}
async function stop(){
  if(!server||server.exitCode!==null)return;
  const exited=new Promise(resolve=>server.once('exit',resolve));
  server.kill();await exited;
}
